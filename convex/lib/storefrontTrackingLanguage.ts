export function storefrontLanguage(requested: string | null) {
  const language = requested?.trim().toLowerCase().split(/[-_]/)[0] || "fr";
  const locale = Object.hasOwn(messages, language) ? (language as keyof typeof messages) : "en";
  return { locale, text: messages[locale] };
}

export type StorefrontLanguage = ReturnType<typeof storefrontLanguage>;
